"""Embeds the de-identified dataset in data/base-data.js so the dashboard also works when opened from disk (file://),
where browsers block fetch() of local files. Run after prepare_data.py:  python scripts/build_base_data.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
csv = (ROOT / "data" / "er_visits_deidentified.csv").read_text(encoding="utf-8")
payload = {"name": "Hospital ER Data (de-identified)", "source": "Hospital_ER_Data.csv, names removed and IDs pseudonymised by scripts/prepare_data.py", "csv": csv}
(ROOT / "data" / "base-data.js").write_text(
    "/* Generated by scripts/build_base_data.py - de-identified base dataset (no names; patient IDs replaced by pseudonymous keys). */\n"
    "window.BASE_DATASET = " + json.dumps(payload) + ";\n", encoding="utf-8")
print("rows:", csv.count("\n") - 1, "bytes:", len(csv))
